/** BR-BH-06: Order chưa PAID thì không giao hàng (`deliveryAllowed = false`). */
export const NOT_DELIVERED_TEXT = 'Chưa thanh toán – chưa giao hàng';

export interface OrderLine {
  lineId: number;
  lineType: OrderLineType;
  serviceId?: number | null;
  productId?: number | null;
  /** Tên chụp lúc thêm dòng. */
  description: string;
  quantity: number;
  /** VND, chụp lúc thêm dòng (BR-BH-03). */
  unitPrice: number;
  lineTotal: number;
  isAutoGenerated: boolean;
  addedBy: number;
  ownerAccountId: number;
  /** Cờ của người đang xem, cùng nguồn với guard của BE (docs/adr/0044 §3). */
  canEdit: boolean;
  canDelete: boolean;
}

export interface Order {
  orderId: number;
  code: string;
  source: OrderSource;
  status: OrderStatus;
  customerId: number;
  customerName: string;
  branchId: number;
  visitId?: number | null;
  boardingBookingId?: number | null;
  totalAmount: number;
  lines: OrderLine[];
  createdAt: string;
  pendingAt?: string | null;
  paidAt?: string | null;
  paymentId?: number | null;
  cancelType?: OrderCancelType | null;
  cancelReason?: string | null;
  cancelledAt?: string | null;
  deliveryAllowed: boolean;
}

export interface OrderSummary {
  orderId: number;
  code: string;
  source: OrderSource;
  status: OrderStatus;
  customerId: number;
  customerName: string;
  branchId: number;
  totalAmount: number;
  createdAt: string;
  pendingAt?: string | null;
  paidAt?: string | null;
}

/** sales-v1 #2: chi nhánh luôn là chi nhánh người gọi; `date` = ngày tạo (giờ Việt Nam). */
export interface OrderQuery {
  status?: OrderStatus;
  source?: OrderSource;
  customerId?: number;
  visitId?: number;
  boardingBookingId?: number;
  date?: string;
  /** PENDING chốt từ N ngày [CFG] `order.pending_alert_days` trở về trước, cũ nhất trước (BR-BH-05, docs/adr/0051 §4.4). */
  pendingOverdue?: boolean;
  page?: number;
  size?: number;
}

/** Lễ tân thêm GOODS; VET / CARETAKER thêm SERVICE (BR-BH-02). */
export interface AddOrderLineRequest {
  lineType: 'SERVICE' | 'GOODS';
  serviceId?: number;
  productId?: number;
  quantity: number;
}

/** `requested` = tổng số lượng sản phẩm trong Order sau khi thêm; `available` = tồn khả dụng của chi nhánh. */
export interface StockWarning {
  productId: number;
  requested: number;
  available: number;
}

export interface AddOrderLineResult {
  order: Order;
  lineId: number;
  /** Có khi thiếu tồn khả dụng — chỉ cảnh báo, không chặn (BR-BH-04). */
  stockWarning?: StockWarning | null;
}

/** PATCH chỉ giảm số lượng (docs/adr/0044 §4.3); `serviceId` chỉ cho dòng dịch vụ tự sinh của Order VISIT. */
export interface UpdateOrderLineRequest {
  quantity?: number;
  serviceId?: number;
}
