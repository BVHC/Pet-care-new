export type OrderLineType = 'SERVICE' | 'GOODS' | 'DRUG' | 'VACCINE' | 'BOARDING';
export type OrderCancelType = 'VISIT_CANCELLED' | 'RETAIL_UNCLOSED' | 'CHECKOUT_ABORTED' | 'UNPAID';

