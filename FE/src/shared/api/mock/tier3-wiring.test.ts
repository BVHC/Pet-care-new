import type { AxiosInstance } from 'axios';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { ACCOUNTS, authAs, failure, makeClient, pinClock } from '../../../test/boarding-harness';

// Nối nghiệp vụ chéo của nhóm Clinical (tier3-wiring.ts): chạy qua mock-api đầy đủ, đồng hồ ghim thứ Sáu 23/10/2026 09:00 (chi nhánh 1 đang mở cửa).
// Lượt 2002 (Lu, IN_PROGRESS) do BS. Minh Anh (#5) phụ trách, Order mở dòng khám tổng quát 150.000 ₫;
// đặt chỗ lưu trú #2 Cốm (CHECKED_IN, chuồng C-01) là chỗ nhập viện từ lưu trú.

let client: AxiosInstance;

beforeEach(() => {
  pinClock();
  client = makeClient();
});
afterEach(() => vi.useRealTimers());

const as = (email: string) => authAs(client, email);
const ruleOf = (res: Awaited<ReturnType<typeof failure>>) => [res.status, res.data.errorCode, /\((BR-[A-Z]+-\d+)\)$/.exec(res.data.message)?.[1]];

interface OrderView {
  orderId: number;
  status: string;
  totalAmount: number;
  lines: {
    lineId: number;
    lineType: string;
    serviceId: number | null;
    productId: number | null;
    description: string;
    quantity: number;
    unitPrice: number;
    isAutoGenerated: boolean;
    canEdit: boolean;
    canDelete: boolean;
  }[];
}
async function orderOf(visitId: number, email: string = ACCOUNTS.desk): Promise<OrderView> {
  const auth = await as(email);
  await client.get(`/api/visits/${visitId}`, auth); // Order của lượt mẫu được dựng lười khi mock lượt khám nạp dữ liệu.
  const { orderId } = (await client.get('/api/orders', { params: { visitId }, ...auth })).data.data.content[0];
  return (await client.get(`/api/orders/${orderId}`, auth)).data.data;
}

const CONSENT = { consentText: 'Rủi ro gây mê, chi phí dự kiến, mổ đường giữa bụng', signerName: 'Lê Hoàng Long', signerRelation: 'Chủ thú' };
/** Lập kế hoạch → cam kết → bắt đầu → hoàn tất phẫu thuật `serviceId` ở lượt `visitId`; trả phẫu thuật đã hoàn tất. */
async function operate(visitId: number, serviceId: number) {
  const doctor = await as(ACCOUNTS.vet);
  const planned = (await client.post(`/api/visits/${visitId}/surgeries`, { serviceId, planNote: 'Ca mẫu' }, doctor)).data.data;
  await client.post(`/api/surgeries/${planned.surgeryId}/consent`, CONSENT, await as(ACCOUNTS.desk));
  await client.post(`/api/surgeries/${planned.surgeryId}/start`, {}, doctor);
  return (await client.post(`/api/surgeries/${planned.surgeryId}/complete`, { resultNote: 'Ổn định, không biến chứng' }, doctor)).data.data as { surgeryId: number; orderLineId: number };
}

describe('phẫu thuật → Order của lượt (VisitOrderApi.addServiceLine, 09 §B)', () => {
  it('hoàn tất: dòng SERVICE thật (tên, giá chụp lúc này), tổng Order tăng đúng giá, dòng không sửa / xóa tay', async () => {
    const before = await orderOf(2002);
    const done = await operate(2002, 7001);
    const after = await orderOf(2002);
    expect(after.lines.find((l) => l.lineId === done.orderLineId)).toMatchObject({
      lineType: 'SERVICE',
      serviceId: 7001,
      description: 'Triệt sản chó mèo',
      quantity: 1,
      unitPrice: 1_800_000,
      isAutoGenerated: false,
      canEdit: false,
      canDelete: false,
    });
    expect(after.totalAmount).toBe(before.totalAmount + 1_800_000);

    const doctor = await as(ACCOUNTS.vet);
    const removed = await failure(client.delete(`/api/orders/${after.orderId}/lines/${done.orderLineId}`, doctor));
    expect(ruleOf(removed)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-BH-02']);
    expect((await orderOf(2002)).lines.some((l) => l.lineId === done.orderLineId)).toBe(true);
  });

  it('dịch vụ phẫu thuật / nội trú không thêm tay vào Order, không đổi dòng tự sinh sang chúng (BR-KB-08, BR-LT-14)', async () => {
    const doctor = await as(ACCOUNTS.vet);
    const order = await orderOf(2002);
    const add = (serviceId: number) => failure(client.post(`/api/orders/${order.orderId}/lines`, { lineType: 'SERVICE', serviceId, quantity: 1 }, doctor));
    expect(ruleOf(await add(7002))).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-KB-08']);
    expect(ruleOf(await add(7101))).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-LT-14']);
    const examLine = order.lines.find((l) => l.isAutoGenerated)!;
    const swap = await failure(client.patch(`/api/orders/${order.orderId}/lines/${examLine.lineId}`, { serviceId: 7001 }, doctor));
    expect(ruleOf(swap)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-KB-08']);
    expect((await orderOf(2002)).lines.find((l) => l.lineId === examLine.lineId)).toMatchObject({ serviceId: 1, unitPrice: 150_000 });
  });

  it('giá và trạng thái lấy từ danh mục: quản lý chuỗi đổi giá thì ca sau tính giá mới, ngừng kinh doanh thì không lập kế hoạch được', async () => {
    const chain = await as(ACCOUNTS.chain);
    await client.patch('/api/services/7001', { price: 2_000_000 }, chain);
    const done = await operate(2002, 7001);
    expect((await orderOf(2002)).lines.find((l) => l.lineId === done.orderLineId)?.unitPrice).toBe(2_000_000);

    await client.patch('/api/services/7002', { isActive: false }, chain);
    const refused = await failure(client.post('/api/visits/2002/surgeries', { serviceId: 7002 }, await as(ACCOUNTS.vet)));
    expect(ruleOf(refused)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-KB-08']);
    expect(refused.data.message).toContain('ngừng');
  });

  it('dịch vụ mẫu mặc định không lộ cho khách: không có trong danh sách công khai, không đặt lịch hay tiếp nhận được (09 BR-KB-08: phẫu thuật chỉ phát sinh từ khám)', async () => {
    const publicIds = ((await client.get('/api/public/services')).data.data as { serviceId: number }[]).map((s) => s.serviceId);
    expect(publicIds.length).toBeGreaterThan(0);
    expect(publicIds.filter((id) => id >= 7000)).toEqual([]);

    const customer = await as(ACCOUNTS.customer);
    const slots = await failure(client.get('/api/branches/1/available-slots', { params: { serviceId: 7001, date: '2026-10-27' }, ...customer }));
    expect(ruleOf(slots)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-LH-01']);
    const book = await failure(client.post('/api/appointments', { petId: 1, serviceId: 7001, branchId: 1, slotDate: '2026-10-27', slotStart: '09:00' }, customer));
    expect(ruleOf(book)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-LH-01']);
    const walkIn = await failure(client.post('/api/visits', { petId: 4, serviceId: 7101 }, await as(ACCOUNTS.desk)));
    expect(ruleOf(walkIn)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-LH-01']);
  });
});

describe('nội trú → Order của lượt và guard trả thú (09 §C, BR-LT-14, BR-LT-17)', () => {
  it('còn ca ADMITTED: bắt đầu trả thú / giao thú 409 BR-LT-17; xuất viện thêm dòng số ngày × giá đã chốt, hết chặn', async () => {
    const doctor = await as(ACCOUNTS.vet);
    const desk = await as(ACCOUNTS.desk);
    const admission = (await client.post('/api/admissions', { boardingBookingId: 2, serviceId: 7101 }, doctor)).data.data as { admissionId: number; visitId: number };

    for (const action of ['start-checkout', 'hand-over']) {
      const refused = await failure(client.post(`/api/boarding-bookings/2/${action}`, undefined, desk));
      expect(ruleOf(refused)).toEqual([409, 'INVALID_STATE_TRANSITION', 'BR-LT-17']);
    }
    // Nhập viện chưa tính tiền: chỉ xuất viện mới thêm dòng.
    expect((await orderOf(admission.visitId)).lines.some((l) => l.serviceId === 7101)).toBe(false);

    const discharged = (await client.post(`/api/admissions/${admission.admissionId}/discharge`, { outcome: 'HOME', summary: 'Ổn định, về nhà' }, doctor)).data.data as { orderLineId: number };
    const order = await orderOf(admission.visitId);
    expect(order.lines.find((l) => l.lineId === discharged.orderLineId)).toMatchObject({
      lineType: 'SERVICE',
      serviceId: 7101,
      description: 'Nội trú điều trị (theo ngày)',
      quantity: 1,
      unitPrice: 350_000,
      canEdit: false,
      canDelete: false,
    });

    expect((await client.post('/api/boarding-bookings/2/start-checkout', undefined, desk)).status).toBe(200);
  });

  it('thú mất (end-deceased) không bị guard BR-LT-17 chặn', async () => {
    await client.post('/api/admissions', { boardingBookingId: 2, serviceId: 7101 }, await as(ACCOUNTS.vet));
    const res = await client.post('/api/boarding-bookings/2/end-deceased', { note: 'Thú mất trong lúc điều trị' }, await as(ACCOUNTS.desk));
    expect(res.status).toBe(200);
  });
});

describe('ST07 — hoàn tất lượt trừ vật tư tiêu hao theo định mức (BR-KB-12…14)', () => {
  it('hoàn tất lượt 2002: mỗi dòng định mức của dịch vụ khám thành một dòng vật tư của lượt', async () => {
    const doctor = await as(ACCOUNTS.vet);
    const norms = (await client.get('/api/services/1/material-norms', await as(ACCOUNTS.chain))).data.data as { productId: number; quantity: number }[];
    expect(norms.length).toBeGreaterThan(0);
    expect((await client.get('/api/visits/2002/material-usages', doctor)).data.data).toEqual([]);

    await client.put('/api/visits/2002/medical-record', { diagnosis: 'Viêm da nhẹ' }, doctor);
    await client.post('/api/visits/2002/complete', {}, doctor);

    const usages = (await client.get('/api/visits/2002/material-usages', doctor)).data.data as {
      visitId: number;
      serviceId: number;
      productId: number;
      normQty: number;
      issuedQty: number;
      shortageQty: number;
    }[];
    expect(usages.map((u) => [u.productId, u.normQty]).sort()).toEqual(norms.map((n) => [n.productId, n.quantity]).sort());
    expect(usages.every((u) => u.visitId === 2002 && u.serviceId === 1 && u.issuedQty + u.shortageQty === u.normQty)).toBe(true);
  });

  it('lượt hoàn tất bị từ chối (BR-KB-02 thiếu chẩn đoán) thì chưa trừ vật tư', async () => {
    const doctor = await as(ACCOUNTS.vet);
    const refused = await failure(client.post('/api/visits/2002/complete', {}, doctor));
    expect(ruleOf(refused)).toEqual([400, 'BUSINESS_RULE_VIOLATION', 'BR-KB-02']);
    expect((await client.get('/api/visits/2002/material-usages', doctor)).data.data).toEqual([]);
  });
});
