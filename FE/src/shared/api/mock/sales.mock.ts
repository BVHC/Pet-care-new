/** #1 Order#2: lễ tân, chi nhánh của lễ tân, khách bắt buộc (A1). */
const createOrder: MockHandler = (req) => {
  const { customerId } = bodyOf(req);
  const bad = invalid([['customerId', 'Vui lòng chọn khách hàng', !has(customerId)]]);
  if (bad) return bad;
  if (notInteger(customerId)) return malformed();
  if (me(req).role !== 'RECEPTIONIST') return denied();
  const id = customerId as number;
  if (!findCustomer(id)) return notFound('khách hàng', id);
  const s = load();
  const now = new Date().toISOString();
  s.codeSeq += 1;
  const row: OrderRow = {
    orderId: ++s.seq,
    code: codeOf(now, s.codeSeq),
    source: 'RETAIL',
    status: 'OPEN',
    customerId: id,
    branchId: me(req).branchId!,
    visitId: null,
    assigneeId: null,
    boardingBookingId: null,
    lines: [],
    createdAt: now,
    pendingAt: null,
    paidAt: null,
    paymentId: null,
    cancelType: null,
    cancelReason: null,
    cancelledBy: null,
    cancelledAt: null,
  };
  s.orders.push(row);
  save(s);
  markHasData(id);
  return ok(view(row, me(req)), 201, 'Đã tạo Order bán lẻ');
};

/** #2: chi nhánh mình; không lọc thì mới nhất trước; `pendingOverdue` thì chốt cũ nhất trước. */
const listOrders: MockHandler = (req) => {
  const { status, source, customerId, visitId, boardingBookingId, date, pendingOverdue } = req.query;
  if (status && !STATUSES.includes(status as OrderStatus)) return fail('VALIDATION_FAILED', 'status: Trạng thái không hợp lệ', 400);
  if (source && !SOURCES.includes(source as OrderSource)) return fail('VALIDATION_FAILED', 'source: Nguồn không hợp lệ', 400);
  if (date && !(DATE.test(date) && !Number.isNaN(Date.parse(date)))) return fail('VALIDATION_FAILED', 'date: Ngày không hợp lệ', 400);
  const overdue = pendingOverdue === 'true';
  const cutoff = overdueCutoff();
  const list = load()
    .orders.filter(
      (o) =>
        o.branchId === me(req).branchId &&
        (!status || o.status === status) &&
        (!source || o.source === source) &&
        (!customerId || o.customerId === Number(customerId)) &&
        (!visitId || o.visitId === Number(visitId)) &&
        (!boardingBookingId || o.boardingBookingId === Number(boardingBookingId)) &&
        (!date || localIsoDate(new Date(o.createdAt)) === date) &&
        (!overdue || (o.status === 'PENDING' && o.pendingAt !== null && Date.parse(o.pendingAt) < cutoff)),
    )
    .sort((a, b) =>
      overdue
        ? Date.parse(a.pendingAt!) - Date.parse(b.pendingAt!) || a.orderId - b.orderId
        : Date.parse(b.createdAt) - Date.parse(a.createdAt) || b.orderId - a.orderId,
    );
  const page = Math.max(Number(req.query.page ?? 0) || 0, 0);
  const size = Math.min(Math.max(Number(req.query.size ?? 20) || 20, 1), 100);
  return ok({
    content: list.slice(page * size, page * size + size).map(summaryOf),
    page,
    size,
    totalElements: list.length,
    totalPages: Math.ceil(list.length / size),
  });
};

const getOrder: MockHandler = (req) => {
  const o = owned(load(), req);
  return isRow(o) ? ok(view(o, me(req))) : o;
};

/** Cảnh báo thiếu tồn, không chặn (BR-BH-04): tổng số lượng sản phẩm trong Order so với tồn khả dụng của chi nhánh. */
function stockWarning(o: OrderRow, productId: number): StockWarning | null {
  const requested = o.lines.filter((l) => l.productId === productId).reduce((sum, l) => sum + l.quantity, 0);
  const available = availableQuantity(o.branchId, productId);
  return available < requested ? { productId, requested, available } : null;
}

function goodsLine(s: State, o: OrderRow, account: AccountSummary, productId: number, quantity: number): LineRow | MockReply {
  if (!acceptsLine(o.status, 'GOODS')) return conflict('đơn hàng (không thêm được dòng này ở trạng thái hiện tại)', o.status, 'OPEN');
  const p = catalogProducts().find((x) => x.productId === productId);
  if (!p) return notFound('sản phẩm', productId);
  if (!p.isActive) return badLine(`Sản phẩm #${p.productId} đã ngừng kinh doanh`);
  if (p.isPrescription) return ruleFail('BR-SP-01', 'Thuốc kê đơn chỉ được đưa vào Order qua kê đơn của bác sĩ');
  if (p.productType === 'VACCINE') return ruleFail('BR-KB-04', 'Vaccine chỉ được đưa vào Order khi ghi nhận mũi tiêm');
  // Giá và tên chụp lúc thêm (BR-BH-03); thêm cùng sản phẩm lần nữa là dòng mới (docs/adr/0044 §4.5).
  return { lineId: ++s.seq, lineType: 'GOODS', serviceId: null, productId: p.productId, description: p.name, quantity, unitPrice: p.price, isAutoGenerated: false, addedBy: account.id, ownerAccountId: account.id };
}

function serviceLine(s: State, o: OrderRow, account: AccountSummary, serviceId: number, quantity: number): LineRow | MockReply {
  const service = catalogServices().find((x) => x.serviceId === serviceId);
  if (!service) return notFound('dịch vụ', serviceId);
  if (SERVICE_GROUP_OF[account.role] !== service.group) return lineDenied();
  if (o.source !== 'VISIT' || o.assigneeId !== account.id) return lineDenied();
  if (!acceptsLine(o.status, 'SERVICE')) return conflict('đơn hàng (không thêm được dòng này ở trạng thái hiện tại)', o.status, 'OPEN');
  if (!service.isActive) return badLine(`Dịch vụ #${service.serviceId} đã ngừng kinh doanh`);
  return { lineId: ++s.seq, lineType: 'SERVICE', serviceId, productId: null, description: service.name, quantity, unitPrice: service.price, isAutoGenerated: false, addedBy: account.id, ownerAccountId: account.id };
}

/** #4: hình dạng 400 → vai trò – loại dòng 403 → Order 404 → chi nhánh 403 → (dịch vụ: nhóm, người phụ trách 403) → 409 → rule 400. */
const addLine: MockHandler = (req) => {
  const b = bodyOf(req);
  const bad = invalid([
    ['lineType', 'Vui lòng chọn loại dòng', !has(b.lineType)],
    ['quantity', 'Vui lòng nhập số lượng', !has(b.quantity)],
    ['quantity', 'Số lượng phải lớn hơn 0', has(b.quantity) && Number(b.quantity) < 1],
    ['quantity', 'Số lượng tối đa 1.000.000', has(b.quantity) && Number(b.quantity) > MAX_QUANTITY],
  ]);
  if (bad) return bad;
  if ((b.lineType !== 'SERVICE' && b.lineType !== 'GOODS') || notInteger(b.quantity) || notInteger(b.productId) || notInteger(b.serviceId)) return malformed();
  const account = me(req);
  if (!LINE_EDITORS.includes(account.role)) return denied();
  const service = b.lineType === 'SERVICE';
  if (service ? !has(b.serviceId) || has(b.productId) : !has(b.productId) || has(b.serviceId)) {
    return badLine(service ? 'Dòng dịch vụ cần serviceId và không có productId' : 'Dòng hàng cần productId và không có serviceId');
  }
  if (service ? !SERVICE_GROUP_OF[account.role] : account.role !== 'RECEPTIONIST') return lineDenied();
  const s = load();
  const o = owned(s, req);
  if (!isRow(o)) return o;
  const quantity = b.quantity as number;
  const line = service ? serviceLine(s, o, account, b.serviceId as number, quantity) : goodsLine(s, o, account, b.productId as number, quantity);
  if (!('lineId' in line)) return line;
  o.lines.push(line);
  save(s);
  const warning = line.productId !== null ? stockWarning(o, line.productId) : null;
  return ok({ order: view(o, account), lineId: line.lineId, stockWarning: warning }, 201, 'Đã thêm dòng vào Order');
};

/** Dòng của Order đã qua kiểm Order / chi nhánh / quyền dòng. */
function editableLine(s: State, req: MockRequest, op: 'EDIT' | 'DELETE'): { o: OrderRow; line: LineRow } | MockReply {
  const o = owned(s, req);
  if (!isRow(o)) return o;
  const line = o.lines.find((l) => l.lineId === Number(req.params.lineId));
  if (!line) return notFound('dòng đơn hàng', req.params.lineId);
  const denial = lineDenial(op, me(req), o, line);
  return denial ? denialReply(denial, o, line) : { o, line };
}

/** #5: chỉ giảm số lượng (docs/adr/0044 §4.3); đổi dịch vụ chỉ cho dòng tự sinh của Order VISIT (A5). */
const updateLine: MockHandler = (req) => {
  const b = bodyOf(req);
  const bad = invalid([
    ['quantity', 'Số lượng phải lớn hơn 0', has(b.quantity) && Number(b.quantity) < 1],
    ['quantity', 'Số lượng tối đa 1.000.000', has(b.quantity) && Number(b.quantity) > MAX_QUANTITY],
  ]);
  if (bad) return bad;
  if (notInteger(b.quantity) || notInteger(b.serviceId)) return malformed();
  const account = me(req);
  if (!LINE_EDITORS.includes(account.role)) return denied();
  if (!has(b.quantity) && !has(b.serviceId)) return badLine('Cần gửi quantity hoặc serviceId');
  const s = load();
  const found = editableLine(s, req, 'EDIT');
  if (!('line' in found)) return found;
  const { o, line } = found;
  if (has(b.quantity)) {
    if ((b.quantity as number) > line.quantity) return badLine('Chỉ được giảm số lượng; muốn thêm hãy thêm dòng mới để được cảnh báo tồn');
    line.quantity = b.quantity as number;
  }
  if (has(b.serviceId)) {
    if (line.lineType !== 'SERVICE' || !line.isAutoGenerated || o.source !== 'VISIT') return badLine('Chỉ đổi được dịch vụ của dòng tự sinh khi tiếp nhận');
    const service = catalogServices().find((x) => x.serviceId === b.serviceId);
    if (!service) return notFound('dịch vụ', String(b.serviceId));
    if (!SERVICE_GROUP_OF[account.role] || service.group !== SERVICE_GROUP_OF[account.role]) return lineDenied();
    if (!service.isActive) return badLine(`Dịch vụ #${service.serviceId} đã ngừng kinh doanh`);
    Object.assign(line, { serviceId: service.serviceId, description: service.name, unitPrice: service.price });
  }
  save(s);
  return ok(view(o, account), 200, 'Đã cập nhật dòng');
};

const deleteLine: MockHandler = (req) => {
  const s = load();
  const found = editableLine(s, req, 'DELETE');
  if (!('line' in found)) return found;
  found.o.lines = found.o.lines.filter((l) => l !== found.line);
  save(s);
  return ok(view(found.o, me(req)), 200, 'Đã xóa dòng');
};

/** #7 Order#5: mọi lễ tân của chi nhánh, không riêng người tạo (docs/adr/0051 §2.1). */
