const me = (req: MockRequest) => req.account!;
const allow = (roles: readonly Role[], h: MockHandler): MockHandler => (req) => (roles.includes(me(req).role) ? h(req) : denied());
const bodyOf = (req: MockRequest) => (req.body ?? {}) as Record<string, unknown>;
const isRow = (x: OrderRow | MockReply): x is OrderRow => 'orderId' in x;
const malformed = () => fail('MALFORMED_REQUEST', 'Dữ liệu gửi lên không đọc được.', 400);
/** ADR-0032: số nguyên JSON nghiêm ngặt. */
const notInteger = (v: unknown) => has(v) && !Number.isInteger(v);

/** Order (404) rồi chi nhánh của người gọi (403), như `lockOwned`. */
function owned(s: State, req: MockRequest): OrderRow | MockReply {
  const o = s.orders.find((x) => x.orderId === Number(req.params.orderId));
  if (!o) return notFound('đơn hàng', req.params.orderId);
  return o.branchId === me(req).branchId ? o : scopeDenied();
}

/** Chốt / hủy chưa chốt: chỉ Order bán lẻ đang OPEN (409 trước rule, docs/adr/0051 §2.3). */
function openRetail(s: State, req: MockRequest, target: OrderStatus): OrderRow | MockReply {
  const o = owned(s, req);
  if (!isRow(o)) return o;
  return o.source === 'RETAIL' && o.status === 'OPEN' ? o : conflict('đơn hàng (chỉ Order bán lẻ đang mở)', o.status, target);
}

/** Mốc "chờ thu quá hạn": chốt trước 00:00 của ngày (hôm nay − N + 1), giờ máy = giờ Việt Nam. */
const overdueCutoff = () => new Date(`${addDays(localIsoDate(), -(PENDING_ALERT_DAYS - 1))}T00:00:00`).getTime();

