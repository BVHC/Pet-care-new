const STATE_KEY = 'petcare-mock-sales';

function load(): State {
  try {
    const raw = localStorage.getItem(STATE_KEY);
    if (raw) return JSON.parse(raw) as State;
  } catch {
    // Dữ liệu hỏng: dùng lại dữ liệu mẫu.
  }
  return seed();
}

function save(s: State) {
  try {
    localStorage.setItem(STATE_KEY, JSON.stringify(s));
  } catch {
    // Không ghi được (chế độ riêng tư): thay đổi chỉ mất khi tải lại.
  }
}

// ─── Quyền dòng (BR-BH-02, docs/adr/0044 §3) ───

type Denial = 'ORDER_FINISHED' | 'NOT_DIRECTLY_EDITABLE' | 'LOCKED_WHEN_PENDING' | 'NOT_OWNER';

function lineDenial(op: 'EDIT' | 'DELETE', me: AccountSummary, o: OrderRow, l: LineRow): Denial | null {
  if (o.status === 'PAID' || o.status === 'CANCELLED') return 'ORDER_FINISHED';
  switch (l.lineType) {
    case 'VACCINE':
    case 'BOARDING':
      return 'NOT_DIRECTLY_EDITABLE';
    case 'DRUG':
      return op === 'EDIT' && o.status === 'PENDING' ? 'LOCKED_WHEN_PENDING' : 'NOT_DIRECTLY_EDITABLE';
    case 'SERVICE':
      if (o.status === 'PENDING') return 'LOCKED_WHEN_PENDING';
      // Dòng tự sinh của Visit: lễ tân tiếp nhận là chủ tạm nhưng không sửa / xóa (sales-v1 A6).
      if (l.isAutoGenerated && o.source === 'VISIT' && me.role === 'RECEPTIONIST') return 'NOT_OWNER';
      return LINE_EDITORS.includes(me.role) && l.ownerAccountId === me.id ? null : 'NOT_OWNER';
    default:
      // GOODS: mọi lễ tân của chi nhánh, cả OPEN lẫn PENDING.
      return me.role === 'RECEPTIONIST' ? null : 'NOT_OWNER';
  }
}

/** OPEN nhận mọi dòng, PENDING chỉ hàng bán lẻ (03 #5). */
const acceptsLine = (status: OrderStatus, type: OrderLineType) => status === 'OPEN' || (status === 'PENDING' && type === 'GOODS');

const conflict = (what: string, from: string, to: string) =>
  fail('INVALID_STATE_TRANSITION', `Không thể chuyển trạng thái ${what} từ ${from} sang ${to}`, 409);
const lineDenied = () => fail('ACCESS_DENIED_SCOPE_MISMATCH', 'Không có quyền thực hiện thao tác này trên dòng đơn hàng (BR-BH-02)', 403);
const badLine = (message: string) => fail('VALIDATION_FAILED', message, 400);

function denialReply(d: Denial, o: OrderRow, l: LineRow): MockReply {
  if (d === 'ORDER_FINISHED') return conflict('đơn hàng (đã kết thúc, không sửa dòng được)', o.status, 'OPEN');
  if (d === 'NOT_DIRECTLY_EDITABLE') {
    const message =
      l.lineType === 'VACCINE'
        ? 'Dòng vaccine không xóa trực tiếp, hãy xóa mũi tiêm'
        : l.lineType === 'DRUG'
          ? 'Dòng thuốc chỉ sửa hoặc xóa qua đơn thuốc'
          : 'Dòng này sinh tự động, không sửa trực tiếp';
    return ruleFail('BR-BH-02', message);
  }
  return lineDenied();
}

