const as = (who: keyof typeof ACCOUNTS) => authAs(client, ACCOUNTS[who]);
const report = async (who: keyof typeof ACCOUNTS, endpoint: string, params: Record<string, unknown> = {}) =>
  client.get(`/api/reports/${endpoint}`, { params, ...(await as(who)) });
const rowsOf = async <T>(who: keyof typeof ACCOUNTS, endpoint: string, params: Record<string, unknown> = {}) =>
  (await report(who, endpoint, params)).data.data.rows as T[];
const rejected = async (who: keyof typeof ACCOUNTS, endpoint: string, params: Record<string, unknown> = {}) =>
  failure(client.get(`/api/reports/${endpoint}`, { params, ...(await as(who)) }));

function expectFail(res: AxiosResponse, status: number, errorCode: string, message?: string | RegExp) {
  expect(res.status).toBe(status);
  expect(res.data).toMatchObject({ success: false, errorCode, statusCode: status });
  if (typeof message === 'string') expect(res.data.message).toBe(message);
  else if (message) expect(res.data.message).toMatch(message);
}

