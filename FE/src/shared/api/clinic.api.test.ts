describe('storage', () => {
  it('starts a fresh day when the stored clinic is from yesterday', () => {
    resetClinicDb(seedClinicDb(NOW - 86_400_000));
    expect(loadDb(NOW).day).toBe(dayKey(NOW));
  });

  it("gives a new day's visits ids never used the day before", async () => {
    const yesterday = await clinicApi.checkIn({ petId: 'pet-dau', serviceId: 'svc-exam', assigneeId: VET }, DESK);
    vi.setSystemTime(NOW + 86_400_000);
    resetClinicDb(seedClinicDb(NOW + 86_400_000));
    const today = await clinicApi.checkIn({ petId: 'pet-dau', serviceId: 'svc-exam', assigneeId: VET }, DESK);
    expect(today.id).not.toBe(yesterday.id);
  });

  it("keeps today's changes across reloads", async () => {
    await clinicApi.callVisit('visit-6', VET);
    expect(loadDb(NOW).visits.find((v) => v.id === 'visit-6')?.status).toBe('IN_PROGRESS');
  });
});
