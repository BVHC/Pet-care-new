package com.petcare.module.sales.entity;

import com.petcare.module.sales.exception.OrderAmountOverflowException;
import com.petcare.platform.model.TimestampedEntity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Getter;
import lombok.NoArgsConstructor;

/**
 * Bảng {@code order_lines} (erd §8, PART của Order). Đơn giá và tên là bản chụp lúc thêm dòng (BR-BH-03);
 * {@code addedBy} không đổi, {@code ownerAccountId} là người có quyền xóa (BR-BH-02, đổi khi gán lại lượt, BR-TN-08).
 * Thành tiền luôn tính lại bằng {@code multiplyExact}: tràn thì 400 thay vì để PostgreSQL báo
 * {@code bigint out of range}.
 */
@Getter
@Entity
@Table(name = "order_lines")
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class OrderLine extends TimestampedEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Enumerated(EnumType.STRING)
    @Column(name = "line_type", nullable = false, updatable = false)
    private OrderLineType lineType;

    @Column(name = "service_id")
    private Long serviceId;

    @Column(name = "product_id", updatable = false)
    private Long productId;

    @Column(name = "description", nullable = false)
    private String description;

    @Column(name = "quantity", nullable = false)
    private int quantity;

    @Column(name = "unit_price", nullable = false)
    private long unitPrice;

    @Column(name = "line_total", nullable = false)
    private long lineTotal;

    @Column(name = "is_auto_generated", nullable = false, updatable = false)
    private boolean autoGenerated;

    @Column(name = "added_by", nullable = false, updatable = false)
    private Long addedBy;

    @Column(name = "owner_account_id", nullable = false)
    private Long ownerAccountId;

    /** Dòng dịch vụ ({@code SERVICE}, {@code BOARDING}) có {@code serviceId}, dòng hàng có {@code productId} (CHECK V1). */
    public static OrderLine of(OrderLineType type, Long serviceId, Long productId, String description, int quantity,
            long unitPrice, boolean autoGenerated, Long addedBy, Long ownerAccountId) {
        OrderLine line = new OrderLine();
        line.lineType = type;
        line.serviceId = serviceId;
        line.productId = productId;
        line.description = description;
        line.quantity = quantity;
        line.unitPrice = unitPrice;
        line.lineTotal = total(quantity, unitPrice);
        line.autoGenerated = autoGenerated;
        line.addedBy = addedBy;
        line.ownerAccountId = ownerAccountId;
        return line;
    }

    /** Giảm số lượng, giữ nguyên đơn giá đã chụp. Caller đã kiểm {@code newQuantity} trong (0, quantity]. */
    public void changeQuantity(int newQuantity) {
        this.quantity = newQuantity;
        this.lineTotal = total(newQuantity, unitPrice);
    }

    /** Đổi dịch vụ của dòng tự sinh: chụp lại tên và giá tại thời điểm đổi (hợp đồng sales-v1 A5). */
    public void replaceService(Long newServiceId, String newDescription, long newUnitPrice) {
        this.serviceId = newServiceId;
        this.description = newDescription;
        this.unitPrice = newUnitPrice;
        this.lineTotal = total(quantity, newUnitPrice);
    }

    public void transferOwnerTo(Long accountId) {
        this.ownerAccountId = accountId;
    }

    private static long total(int quantity, long unitPrice) {
        try {
            return Math.multiplyExact((long) quantity, unitPrice);
        } catch (ArithmeticException e) {
            throw new OrderAmountOverflowException();
        }
    }
}
