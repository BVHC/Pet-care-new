package com.petcare.module.sales.mapper;

import java.util.List;

import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.ReportingPolicy;

import com.petcare.module.sales.dto.OrderLineResponse;
import com.petcare.module.sales.dto.OrderResponse;
import com.petcare.module.sales.entity.OrderLine;
import com.petcare.module.sales.entity.SalesOrder;

/** Order (sales-v1 {@code Order}, {@code OrderLine}); tên khách và cờ quyền do service tính và truyền vào. */
@Mapper(componentModel = "spring", unmappedTargetPolicy = ReportingPolicy.ERROR)
public interface OrderMapper {

    @Mapping(target = "lineId", source = "line.id")
    @Mapping(target = "lineType", source = "line.lineType")
    @Mapping(target = "serviceId", source = "line.serviceId")
    @Mapping(target = "productId", source = "line.productId")
    @Mapping(target = "description", source = "line.description")
    @Mapping(target = "quantity", source = "line.quantity")
    @Mapping(target = "unitPrice", source = "line.unitPrice")
    @Mapping(target = "lineTotal", source = "line.lineTotal")
    @Mapping(target = "autoGenerated", source = "line.autoGenerated")
    @Mapping(target = "addedBy", source = "line.addedBy")
    @Mapping(target = "ownerAccountId", source = "line.ownerAccountId")
    @Mapping(target = "canEdit", source = "canEdit")
    @Mapping(target = "canDelete", source = "canDelete")
    OrderLineResponse toLine(OrderLine line, boolean canEdit, boolean canDelete);

    @Mapping(target = "orderId", source = "order.id")
    @Mapping(target = "code", source = "order.code")
    @Mapping(target = "source", source = "order.source")
    @Mapping(target = "status", source = "order.status")
    @Mapping(target = "customerId", source = "order.customerId")
    @Mapping(target = "customerName", source = "customerName")
    @Mapping(target = "branchId", source = "order.branchId")
    @Mapping(target = "visitId", source = "order.visitId")
    @Mapping(target = "boardingBookingId", source = "order.boardingBookingId")
    @Mapping(target = "totalAmount", source = "order.totalAmount")
    @Mapping(target = "lines", source = "lineResponses")
    @Mapping(target = "createdAt", source = "order.createdAt")
    @Mapping(target = "pendingAt", source = "order.pendingAt")
    @Mapping(target = "paidAt", source = "order.paidAt")
    @Mapping(target = "paymentId", source = "order.paymentId")
    @Mapping(target = "cancelType", source = "order.cancelType")
    @Mapping(target = "cancelReason", source = "order.cancelReason")
    @Mapping(target = "cancelledAt", source = "order.cancelledAt")
    @Mapping(target = "deliveryAllowed",
            expression = "java(order.getStatus() == com.petcare.module.sales.entity.OrderStatus.PAID)")
    OrderResponse toResponse(SalesOrder order, String customerName, List<OrderLineResponse> lineResponses);
}
