package com.petcare.module.sales.service;

import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.util.List;

import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import com.petcare.module.catalog.api.CatalogQueryApi;
import com.petcare.module.catalog.api.CatalogQueryApi.ProductInfo;
import com.petcare.module.catalog.api.CatalogQueryApi.ServiceInfo;
import com.petcare.module.catalog.api.ProductType;
import com.petcare.module.sales.api.VisitOrderApi;
import com.petcare.module.sales.entity.OrderCancelType;
import com.petcare.module.sales.entity.OrderLine;
import com.petcare.module.sales.entity.OrderLineType;
import com.petcare.module.sales.entity.OrderStatus;
import com.petcare.module.sales.entity.SalesOrder;
import com.petcare.module.sales.exception.OrderLineAccessDeniedException;
import com.petcare.module.sales.fsm.OrderTransitionHandler;
import com.petcare.module.sales.repository.SalesOrderRepository;
import com.petcare.platform.exception.ResourceNotFoundException;
import com.petcare.platform.sequence.DocumentCodeGenerator;

import lombok.RequiredArgsConstructor;

/**
 * {@link VisitOrderApi} thật (T19, docs/adr/0044): Order nguồn VISIT cho Visit của BE-1. Mọi method
 * {@code MANDATORY} (chạy trong transaction của Visit) và <b>khóa dòng Order trước khi đọc</b>. Bên gọi (visit) tự khóa
 * Visit của mình trước, nên thứ tự là {@code visits → orders → products (FOR SHARE) → lô kho}. Visit chưa có Order,
 * sai loại sản phẩm… là lỗi của bên gọi (visit đã kiểm BR-LH-01, BR-KB-03, BR-KB-04) nên ném
 * {@code IllegalStateException} / {@code IllegalArgumentException}; Order sai trạng thái là 409.
 */
@Service
@RequiredArgsConstructor
public class VisitOrderService implements VisitOrderApi {

    static final String DOC_TYPE = "ORDER";
    static final String PREFIX = "DH";

    private final SalesOrderRepository orders;
    private final CatalogQueryApi catalog;
    private final DocumentCodeGenerator codes;
    private final OrderTransitionHandler fsm;
    private final Clock clock;

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public LineRef openForVisit(Long visitId, Long branchId, Long customerId, Long serviceId, Long ownerAccountId,
            Long actorId) {
        ServiceInfo service = catalog.findService(serviceId)
                .filter(ServiceInfo::active)
                .orElseThrow(() -> new IllegalStateException("Dịch vụ #" + serviceId + " không tồn tại hoặc đã ngừng"));
        SalesOrder order = SalesOrder.openForVisit(codes.next(DOC_TYPE, PREFIX, LocalDate.now(clock)), branchId,
                customerId, visitId, actorId);
        OrderLine line = OrderLine.of(OrderLineType.SERVICE, serviceId, null, service.name(), 1, service.price(),
                true, actorId, ownerAccountId != null ? ownerAccountId : actorId);
        order.addLine(line);
        orders.saveAndFlush(order);
        return new LineRef(order.getId(), line.getId());
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public void setAutoLineOwner(Long visitId, Long assigneeId) {
        SalesOrder order = lockOpenByVisit(visitId);
        order.getLines().stream().filter(OrderLine::isAutoGenerated).forEach(l -> l.transferOwnerTo(assigneeId));
        orders.flush();
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public void transferLineOwnership(Long visitId, Long fromAccountId, Long toAccountId) {
        SalesOrder order = lockOpenByVisit(visitId);
        order.getLines().stream().filter(l -> fromAccountId.equals(l.getOwnerAccountId()))
                .forEach(l -> l.transferOwnerTo(toAccountId));
        orders.flush();
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public void markPendingByVisit(Long visitId) {
        SalesOrder order = lockByVisit(visitId);
        fsm.validateTransition(order.getStatus(), OrderStatus.PENDING);
        order.markPending(Instant.now(clock));
        orders.flush();
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public void cancelByVisit(Long visitId, Long actorId) {
        SalesOrder order = lockByVisit(visitId);
        // Order#6 chỉ OPEN → CANCELLED; PENDING → CANCELLED (#9, #10) là chuyển khác, do người khác kích hoạt
        OrderGuards.requireOpen(order);
        fsm.validateTransition(order.getStatus(), OrderStatus.CANCELLED);
        order.cancel(OrderCancelType.VISIT_CANCELLED, actorId, null, Instant.now(clock));
        orders.flush();
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public List<Long> findServiceIds(Long visitId) {
        SalesOrder order = orders.findByVisitId(visitId)
                .orElseThrow(() -> new IllegalStateException("Visit #" + visitId + " chưa có Order"));
        return order.getLines().stream().filter(l -> l.getLineType() == OrderLineType.SERVICE)
                .map(OrderLine::getServiceId).toList();
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public LineRef addDrugLine(Long visitId, Long productId, int quantity, Long actorId) {
        requirePositive(quantity);
        SalesOrder order = lockOpenByVisit(visitId);
        ProductInfo product = requireProduct(productId, ProductType.DRUG);
        if (!product.prescription()) {
            throw new IllegalArgumentException("Sản phẩm #" + productId + " không phải thuốc kê đơn (BR-KB-03)");
        }
        return addLine(order, OrderLine.of(OrderLineType.DRUG, null, productId, product.name(), quantity,
                product.price(), false, actorId, actorId));
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public void removeDrugLine(Long orderLineId, Long actorId) {
        SalesOrder order = lockByLine(orderLineId);
        OrderLine line = lineOf(order, orderLineId, OrderLineType.DRUG);
        OrderGuards.requireOpen(order);
        if (!actorId.equals(line.getOwnerAccountId())) {
            throw new OrderLineAccessDeniedException("owner:" + line.getOwnerAccountId(), "account:" + actorId);
        }
        removeLine(order, line);
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public LineRef addVaccineLine(Long visitId, Long productId, Long actorId) {
        SalesOrder order = lockOpenByVisit(visitId);
        ProductInfo product = requireProduct(productId, ProductType.VACCINE);
        return addLine(order, OrderLine.of(OrderLineType.VACCINE, null, productId, product.name(), 1,
                product.price(), false, actorId, actorId));
    }

    @Override
    @Transactional(propagation = Propagation.MANDATORY)
    public void removeVaccineLine(Long orderLineId) {
        SalesOrder order = lockByLine(orderLineId);
        OrderLine line = lineOf(order, orderLineId, OrderLineType.VACCINE);
        OrderGuards.requireOpen(order);
        removeLine(order, line);
    }

    // ---------------------------------------------------------------- nội bộ

    private SalesOrder lockByVisit(Long visitId) {
        return orders.findByVisitIdForUpdate(visitId)
                .orElseThrow(() -> new IllegalStateException("Visit #" + visitId + " chưa có Order"));
    }

    private SalesOrder lockOpenByVisit(Long visitId) {
        SalesOrder order = lockByVisit(visitId);
        OrderGuards.requireOpen(order);
        return order;
    }

    /** Tìm Order chứa dòng (đọc không khóa) → khóa Order → đọc lại dưới khóa (dòng có thể vừa bị xóa). */
    private SalesOrder lockByLine(Long orderLineId) {
        Long orderId = orders.findIdByLineId(orderLineId)
                .orElseThrow(() -> new ResourceNotFoundException("dòng đơn hàng", orderLineId));
        return orders.findByIdForUpdate(orderId)
                .orElseThrow(() -> new ResourceNotFoundException("dòng đơn hàng", orderLineId));
    }

    private static OrderLine lineOf(SalesOrder order, Long orderLineId, OrderLineType expected) {
        OrderLine line = order.findLine(orderLineId)
                .orElseThrow(() -> new ResourceNotFoundException("dòng đơn hàng", orderLineId));
        if (line.getLineType() != expected) {
            throw new IllegalArgumentException("Dòng #" + orderLineId + " không phải dòng " + expected);
        }
        return line;
    }

    /** Sản phẩm đọc bằng {@code FOR SHARE}: đổi giá song song bị xếp hàng, giá chụp là giá vừa commit (BR-BH-03). */
    private ProductInfo requireProduct(Long productId, ProductType type) {
        ProductInfo product = catalog.findProductForShare(productId)
                .orElseThrow(() -> new IllegalStateException("Sản phẩm #" + productId + " không tồn tại"));
        if (product.type() != type || !product.active()) {
            throw new IllegalArgumentException("Sản phẩm #" + productId + " phải là " + type + " đang kinh doanh");
        }
        return product;
    }

    private LineRef addLine(SalesOrder order, OrderLine line) {
        order.addLine(line);
        orders.flush();
        return new LineRef(order.getId(), line.getId());
    }

    private void removeLine(SalesOrder order, OrderLine line) {
        order.removeLine(line);
        orders.flush();
    }

    private static void requirePositive(int quantity) {
        if (quantity <= 0) {
            throw new IllegalArgumentException("Số lượng phải lớn hơn 0");
        }
    }
}
