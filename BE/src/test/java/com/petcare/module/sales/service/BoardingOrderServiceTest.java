package com.petcare.module.sales.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.inOrder;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.never;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import java.time.Clock;
import java.time.Instant;
import java.time.LocalDate;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Optional;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.mockito.InOrder;
import org.springframework.test.util.ReflectionTestUtils;

import com.petcare.module.sales.api.BoardingOrderApi.BoardingCharge;
import com.petcare.module.sales.api.BoardingOrderApi.BoardingOrderRef;
import com.petcare.module.sales.api.OrderSource;
import com.petcare.module.sales.entity.OrderLine;
import com.petcare.module.sales.entity.OrderLineType;
import com.petcare.module.sales.entity.OrderStatus;
import com.petcare.module.sales.entity.SalesOrder;
import com.petcare.module.sales.fsm.OrderTransitionHandler;
import com.petcare.module.sales.repository.SalesOrderRepository;
import com.petcare.platform.exception.InvalidStateTransitionException;
import com.petcare.platform.sequence.DocumentCodeGenerator;

class BoardingOrderServiceTest {

    private static final Instant NOW = Instant.parse("2009-06-12T06:00:00Z");

    private SalesOrderRepository orders;
    private DocumentCodeGenerator codes;
    private BoardingOrderService service;

    private static BoardingCharge charge(int nights, long price) {
        return new BoardingCharge(88L, 7L, 14L, 5L, "Luu tru Chuong cho nho · LT-1", nights, price, 3L);
    }

    @BeforeEach
    void setUp() {
        orders = mock(SalesOrderRepository.class);
        codes = mock(DocumentCodeGenerator.class);
        when(codes.next("ORDER", "DH", LocalDate.parse("2009-06-12"))).thenReturn("DH-0906-00001");
        when(orders.findUnfinishedByBookingForUpdate(88L)).thenReturn(Optional.empty());
        when(orders.existsByBoardingBookingIdAndStatus(88L, OrderStatus.PAID)).thenReturn(false);
        when(orders.saveAndFlush(any())).thenAnswer(i -> {
            SalesOrder saved = i.getArgument(0);
            ReflectionTestUtils.setField(saved, "id", 501L);
            return saved;
        });
        service = new BoardingOrderService(orders, codes, new OrderTransitionHandler(),
                Clock.fixed(NOW, ZoneOffset.UTC));
    }

    private SalesOrder saved() {
        ArgumentCaptor<SalesOrder> captor = ArgumentCaptor.forClass(SalesOrder.class);
        verify(orders).saveAndFlush(captor.capture());
        return captor.getValue();
    }

    @Test
    void createsPendingBoardingOrderWithOneSnapshotLine() {
        BoardingOrderRef ref = service.openOrReuse(charge(3, 150_000L));

        SalesOrder order = saved();
        assertThat(order.getSource()).isEqualTo(OrderSource.BOARDING);
        assertThat(order.getStatus()).isEqualTo(OrderStatus.PENDING);
        assertThat(order.getBoardingBookingId()).isEqualTo(88L);
        assertThat(order.getPendingAt()).isEqualTo(NOW);
        assertThat(order.getLines()).singleElement().satisfies(l -> {
            assertThat(l.getLineType()).isEqualTo(OrderLineType.BOARDING);
            assertThat(l.getServiceId()).isEqualTo(5L);
            assertThat(l.getQuantity()).isEqualTo(3);
            assertThat(l.getUnitPrice()).isEqualTo(150_000L);
            assertThat(l.isAutoGenerated()).isTrue();
        });
        assertThat(ref).isEqualTo(new BoardingOrderRef(501L, 3, 450_000L));
    }

    @Test
    void reusesPendingOrderAndRepricesNightsWithoutNewCode() {
        SalesOrder existing = SalesOrder.openForBoarding("DH-0906-00000", 7L, 14L, 88L, 3L,
                Instant.parse("2009-06-11T06:00:00Z"));
        existing.addLine(OrderLine.of(OrderLineType.BOARDING, 5L, null, "Luu tru", 2, 150_000L, true, 3L, 3L));
        when(orders.findUnfinishedByBookingForUpdate(88L)).thenReturn(Optional.of(existing));

        BoardingOrderRef ref = service.openOrReuse(charge(4, 150_000L));

        assertThat(existing.getTotalAmount()).isEqualTo(600_000L);
        assertThat(existing.getPendingAt()).isEqualTo(Instant.parse("2009-06-11T06:00:00Z"));
        assertThat(ref.nights()).isEqualTo(4);
        verify(codes, never()).next(any(), any(), any());
    }

    @Test
    void paidOrderIsConflictAndWritesNothing() {
        when(orders.existsByBoardingBookingIdAndStatus(88L, OrderStatus.PAID)).thenReturn(true);

        assertThatThrownBy(() -> service.openOrReuse(charge(2, 150_000L)))
                .isInstanceOf(InvalidStateTransitionException.class);

        verify(orders, never()).saveAndFlush(any());
        verify(codes, never()).next(any(), any(), any());
    }

    @Test
    void locksUnfinishedOrderBeforeCheckingPaidThenWrites() {
        service.openOrReuse(charge(2, 150_000L));

        InOrder order = inOrder(orders, codes);
        order.verify(orders).findUnfinishedByBookingForUpdate(88L);
        order.verify(orders).existsByBoardingBookingIdAndStatus(88L, OrderStatus.PAID);
        order.verify(codes).next("ORDER", "DH", LocalDate.parse("2009-06-12"));
        order.verify(orders).saveAndFlush(any());
    }

    @Test
    void findActiveOrderIdsOfEmptySetTouchesNothing() {
        assertThat(service.findActiveOrderIds(List.of())).isEmpty();

        verifyNoInteractions(orders);
    }
}
