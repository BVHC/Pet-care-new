package com.petcare.module.sales.service;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.mockito.Mockito.when;

import java.lang.reflect.Method;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.List;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mockito.ArgumentCaptor;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.annotation.Propagation;
import org.springframework.transaction.annotation.Transactional;

import com.petcare.module.sales.api.OnlineSalesOrderApi;
import com.petcare.module.sales.api.OnlineSalesOrderApi.OnlineOrderLineInput;
import com.petcare.module.sales.api.OrderSource;
import com.petcare.module.sales.entity.OrderLine;
import com.petcare.module.sales.entity.OrderLineType;
import com.petcare.module.sales.entity.OrderStatus;
import com.petcare.module.sales.entity.SalesOrder;
import com.petcare.module.sales.fsm.OrderTransitionHandler;
import com.petcare.module.sales.repository.SalesOrderRepository;

class OnlineSalesOrderServiceTest {

    private static final Instant NOW = Instant.parse("2026-11-17T03:00:00Z");

    private SalesOrderRepository orders;
    private OnlineSalesOrderService service;

    @BeforeEach
    void setUp() {
        orders = mock(SalesOrderRepository.class);
        when(orders.saveAndFlush(any())).thenAnswer(i -> {
            SalesOrder saved = i.getArgument(0);
            ReflectionTestUtils.setField(saved, "id", 901L);
            return saved;
        });
        service = new OnlineSalesOrderService(orders, new OrderTransitionHandler(), Clock.fixed(NOW, ZoneOffset.UTC));
    }

    @Test
    void writesAPendingOrderWithSnapshotGoodsLinesAndTheRecomputedTotal() {
        Long id = service.createPendingOrder("DH-2611-00007", 4L, 14L, 21L, List.of(
                new OnlineOrderLineInput(30L, "Hat A", 2, 50_000L), new OnlineOrderLineInput(31L, "Cat B", 1, 120_000L)));

        assertThat(id).isEqualTo(901L);
        ArgumentCaptor<SalesOrder> captor = ArgumentCaptor.forClass(SalesOrder.class);
        verify(orders).saveAndFlush(captor.capture());
        SalesOrder order = captor.getValue();
        assertThat(order.getCode()).isEqualTo("DH-2611-00007");
        assertThat(order.getSource()).isEqualTo(OrderSource.ONLINE);
        assertThat(order.getStatus()).isEqualTo(OrderStatus.PENDING);
        assertThat(order.getPendingAt()).isEqualTo(NOW);
        assertThat(order.getBranchId()).isEqualTo(4L);
        assertThat(order.getCustomerId()).isEqualTo(14L);
        assertThat(order.getCreatedBy()).isEqualTo(21L);
        assertThat(order.getTotalAmount()).isEqualTo(220_000L);
        assertThat(order.getLines()).extracting(OrderLine::getLineType).containsOnly(OrderLineType.GOODS);
        assertThat(order.getLines()).extracting(OrderLine::getProductId).containsExactly(30L, 31L);
        assertThat(order.getLines()).extracting(OrderLine::getDescription).containsExactly("Hat A", "Cat B");
        assertThat(order.getLines()).extracting(OrderLine::getUnitPrice).containsExactly(50_000L, 120_000L);
        assertThat(order.getLines()).extracting(OrderLine::getLineTotal).containsExactly(100_000L, 120_000L);
        assertThat(order.getLines()).allSatisfy(l -> assertThat(l.isAutoGenerated()).isFalse());
    }

    @Test
    void badInputIsRefusedAndNothingIsWritten() {
        assertThatThrownBy(() -> service.createPendingOrder("C", 1L, 2L, 3L, List.of()))
                .isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> service.createPendingOrder("C", 1L, 2L, 3L,
                List.of(new OnlineOrderLineInput(1L, "x", 0, 10L)))).isInstanceOf(IllegalArgumentException.class);
        assertThatThrownBy(() -> service.createPendingOrder("C", 1L, 2L, 3L,
                List.of(new OnlineOrderLineInput(1L, "x", 1, -1L)))).isInstanceOf(IllegalArgumentException.class);
        verifyNoInteractions(orders);
    }

    @Test
    void runsOnlyInsideTheCallersTransactionAndLocksNothing() throws NoSuchMethodException {
        Method method = OnlineSalesOrderService.class.getMethod("createPendingOrder", String.class, Long.class,
                Long.class, Long.class, List.class);

        assertThat(method.getAnnotation(Transactional.class).propagation()).isEqualTo(Propagation.MANDATORY);
        assertThat(OnlineSalesOrderApi.class).isAssignableFrom(OnlineSalesOrderService.class);
    }
}
