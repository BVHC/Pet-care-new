package com.petcare.module.sales.mapper;

import static org.assertj.core.api.Assertions.assertThat;

import java.time.Instant;
import java.util.List;

import org.junit.jupiter.api.Test;
import org.mapstruct.factory.Mappers;
import org.springframework.test.util.ReflectionTestUtils;

import com.petcare.module.sales.api.OrderSource;
import com.petcare.module.sales.dto.OrderLineResponse;
import com.petcare.module.sales.dto.OrderResponse;
import com.petcare.module.sales.entity.OrderCancelType;
import com.petcare.module.sales.entity.OrderLine;
import com.petcare.module.sales.entity.OrderLineType;
import com.petcare.module.sales.entity.OrderStatus;
import com.petcare.module.sales.entity.SalesOrder;

/** Mỗi trường nhận một giá trị khác nhau để ánh xạ nhầm nguồn bị lộ; so sánh nguyên bản ghi. */
class OrderMapperTest {

    private final OrderMapper mapper = Mappers.getMapper(OrderMapper.class);

    @Test
    void lineKeepsEveryColumnAndTheViewerFlags() {
        OrderLine line = OrderLine.of(OrderLineType.SERVICE, 10L, null, "Khám tổng quát", 2, 150_000, true, 7L, 8L);
        ReflectionTestUtils.setField(line, "id", 31L);

        OrderLineResponse response = mapper.toLine(line, true, false);

        assertThat(response).isEqualTo(new OrderLineResponse(31L, OrderLineType.SERVICE, 10L, null, "Khám tổng quát",
                2, 150_000, 300_000, true, 7L, 8L, true, false));
    }

    @Test
    void goodsLineHasProductAndNoService() {
        OrderLine line = OrderLine.of(OrderLineType.GOODS, null, 20L, "Hạt", 1, 40_000, false, 7L, 7L);

        OrderLineResponse response = mapper.toLine(line, false, true);

        assertThat(response.serviceId()).isNull();
        assertThat(response.productId()).isEqualTo(20L);
        assertThat(response.autoGenerated()).isFalse();
        assertThat(response.canEdit()).isFalse();
        assertThat(response.canDelete()).isTrue();
    }

    @Test
    void orderCopiesEveryContractFieldAndDeliveryFollowsPaid() {
        SalesOrder order = SalesOrder.openForVisit("DH-2610-00009", 2L, 5L, 61L, 3L);
        Instant created = Instant.parse("2026-10-17T03:00:00Z");
        Instant pending = Instant.parse("2026-10-17T04:00:00Z");
        Instant cancelled = Instant.parse("2026-10-17T04:20:00Z");
        ReflectionTestUtils.setField(order, "id", 101L);
        ReflectionTestUtils.setField(order, "createdAt", created);
        ReflectionTestUtils.setField(order, "totalAmount", 190_000L);
        ReflectionTestUtils.setField(order, "pendingAt", pending);
        ReflectionTestUtils.setField(order, "cancelledAt", cancelled);
        ReflectionTestUtils.setField(order, "cancelType", OrderCancelType.UNPAID);
        ReflectionTestUtils.setField(order, "cancelReason", "Khách bỏ về");
        ReflectionTestUtils.setField(order, "status", OrderStatus.CANCELLED);
        List<OrderLineResponse> lines = List.of(new OrderLineResponse(1L, OrderLineType.GOODS, null, 20L, "Hạt", 1,
                190_000, 190_000, false, 3L, 3L, false, false));

        OrderResponse response = mapper.toResponse(order, "Nguyễn Văn An", lines);

        assertThat(response).isEqualTo(new OrderResponse(101L, "DH-2610-00009", OrderSource.VISIT,
                OrderStatus.CANCELLED, 5L, "Nguyễn Văn An", 2L, 61L, null, 190_000, lines, created, pending, null,
                null, OrderCancelType.UNPAID, "Khách bỏ về", cancelled, false));

        ReflectionTestUtils.setField(order, "status", OrderStatus.PAID);
        assertThat(mapper.toResponse(order, "x", lines).deliveryAllowed()).isTrue();
        for (OrderStatus status : List.of(OrderStatus.OPEN, OrderStatus.PENDING, OrderStatus.CANCELLED)) {
            ReflectionTestUtils.setField(order, "status", status);
            assertThat(mapper.toResponse(order, "x", lines).deliveryAllowed()).as(status.name()).isFalse();
        }
    }
}
